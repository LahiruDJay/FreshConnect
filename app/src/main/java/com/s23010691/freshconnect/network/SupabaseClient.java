    /*
     * Registers a new user with email and password.
     * Parameters:
     *   - email: The user's email address.
     *   - password: The user's password.
     *   - name: The user's full name.
     *   - callback: Callback to handle success or error.
     */
    public void signUp(String email, String password, String name, AuthCallback callback) {
        JsonObject jsonBody = new JsonObject();
        jsonBody.addProperty("email", email);
        jsonBody.addProperty("password", password);
        
        JsonObject data = new JsonObject();
        data.addProperty("name", name);
        jsonBody.add("data", data);

        RequestBody body = RequestBody.create(gson.toJson(jsonBody), JSON);

        Request request = new Request.Builder()
                .url(SUPABASE_URL + "/auth/v1/signup")
                .addHeader("apikey", SUPABASE_KEY)
                .addHeader("Authorization", "Bearer " + SUPABASE_KEY)
                .post(body)
                .build();

        client.newCall(request).enqueue(new Callback() {
            @Override
            public void onFailure(Call call, IOException e) {
                runOnMain(() -> callback.onError("Network error: " + e.getMessage()));
            }

            @Override
            public void onResponse(Call call, Response response) throws IOException {
                if (response.isSuccessful()) {
                    try {
                        String bodyStr = response.body().string();
                        JsonObject resJson = gson.fromJson(bodyStr, JsonObject.class);
                        currentAccessToken = resJson.get("access_token").getAsString();
                        currentUserId = resJson.getAsJsonObject("user").get("id").getAsString();
                        currentUserEmail = email;
                    } catch (Exception e) {
                        currentUserEmail = email;
                    }
                    // Signup in auth was successful, now save to public.user table
                    saveUserDetails(currentUserId, email, name, callback);
                } else {
                    String err = parseError(response.body().string());
                    runOnMain(() -> callback.onError("Sign up failed: " + err));
                }
            }
        });
    }

