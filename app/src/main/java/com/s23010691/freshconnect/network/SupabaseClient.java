    /*
     * Uploads a product image to Supabase storage.
     * Parameters:
     *   - bitmap: The image bitmap to upload.
     *   - fileName: The name to save the file as.
     *   - callback: Callback returning the public URL on success.
     */
    public void uploadProductImage(Bitmap bitmap, String fileName, UploadCallback callback) {
        if (currentAccessToken == null) {
            runOnMain(() -> callback.onError("Not authenticated"));
            return;
        }

        ByteArrayOutputStream bos = new ByteArrayOutputStream();
        bitmap.compress(Bitmap.CompressFormat.JPEG, 80, bos);
        byte[] bitmapData = bos.toByteArray();

        RequestBody requestBody = RequestBody.create(bitmapData, MediaType.parse("image/jpeg"));

        Request request = new Request.Builder()
                .url(SUPABASE_URL + "/storage/v1/object/product-images/" + fileName)
                .addHeader("apikey", SUPABASE_KEY)
                .addHeader("Authorization", "Bearer " + currentAccessToken)
                .post(requestBody)
                .build();

        client.newCall(request).enqueue(new Callback() {
            @Override
            public void onFailure(Call call, IOException e) {
                runOnMain(() -> callback.onError("Network error: " + e.getMessage()));
            }

            @Override
            public void onResponse(Call call, Response response) throws IOException {
                if (response.isSuccessful()) {
                    String publicUrl = SUPABASE_URL + "/storage/v1/object/public/product-images/" + fileName;
                    runOnMain(() -> callback.onSuccess(publicUrl));
                } else {
                    String err = parseError(response.body().string());
                    runOnMain(() -> callback.onError("Upload failed: " + err));
                }
            }
        });
    }

